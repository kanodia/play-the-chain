"""Embed the pages in src/ui/ into src/ui_html.h, so the canister can serve them.

Run from the project root after editing a page:  python3 -I scripts/embed_ui.py
"""

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGES = {"HOME_HTML": "home.html", "UI_HTML": "index.html", "GAMES_HTML": "games.html", "GOLF_HTML": "golf.html", "MINIGOLF_HTML": "minigolf.html", "FEED_HTML": "feed.html"}

import hashlib

# The fabric (shared WebGL backdrop and glass styles). Pages ask for it with a
# hash of its contents, so browsers keep it for a year yet see every change.
fabric_js = (ROOT / "src/ui/fabric.js").read_text(encoding="utf-8")
fabric_css = (ROOT / "src/ui/fabric.css").read_text(encoding="utf-8")
version = hashlib.sha256((fabric_js + fabric_css).encode()).hexdigest()[:10]

out = "// Generated by scripts/embed_ui.py from src/ui/*. Do not edit.\n#pragma once\n"
for name, src in [("FABRIC_JS", fabric_js), ("FABRIC_CSS", fabric_css)]:
    assert ')JS"' not in src
    out += f'\nstatic const char {name}[] = R"JS({src})JS";\n'
# Link previews (Open Graph and X cards), the same tags on every page. The
# canister fills in __OG_TITLE__, __OG_DESC__, __OG_IMAGE__ and __OG_URL__ per
# request, so a shared round gets its own headline.
OG_TAGS = """<meta property="og:type" content="website">
<meta property="og:site_name" content="Play the Chain">
<meta property="og:title" content="__OG_TITLE__">
<meta property="og:description" content="__OG_DESC__">
<meta property="og:url" content="__OG_URL__">
<meta property="og:image" content="__OG_IMAGE__">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="__OG_TITLE__">
<meta name="twitter:description" content="__OG_DESC__">
<meta name="twitter:image" content="__OG_IMAGE__">
"""
# Analytics: ptcTrack(event) counts a funnel step in the canister (POST
# /api/event, daily counters only) and in Umami, when UMAMI_ID is set. Umami
# keeps no cookies; data-domains keeps local test networks out of it. Once a
# visit, the page says whether this browser has been here before.
UMAMI_ID = "e9e6a912-fa89-4868-8068-7115dd8ac132"
TRACK = """<script>
window.ptcTrack = (name, data) => {
  try { fetch("/api/event", { method: "POST", body: name, keepalive: true }).catch(() => {}); } catch (e) {}
  try { window.umami && window.umami.track(name, data); } catch (e) {}
};
// The level ladder, shared by the games: levels 1..20, unlocked one at a
// time by winning, remembered per game in this browser.
window.ptcLevels = (game) => {
  const key = "ptc-" + game, get = (k, d) => { try { const v = +localStorage.getItem(key + k); return v >= 1 && v <= 20 ? v : d; } catch (e) { return d; } };
  const put = (k, v) => { try { localStorage.setItem(key + k, String(v)); } catch (e) {} };
  return {
    unlocked: () => get("-unlocked", 1),
    current: () => Math.min(get("-level", 1), get("-unlocked", 1)),
    set: (n) => put("-level", n),
    unlock: (n) => { if (n <= 20 && n > get("-unlocked", 1)) { put("-unlocked", n); return true; } return false; },
  };
};
// Draws the ladder into `box`: ◀ Level n ▶, what the level is like, and how
// far this browser has unlocked. onChange(n) runs when the player moves.
window.ptcLadder = (box, game, describe, onChange) => {
  const lv = window.ptcLevels(game);
  box.classList.add("ladder");
  box.innerHTML = `<button type="button" class="lv-step" data-d="-1" aria-label="Easier level">◀</button>
    <div class="lv-mid"><b class="lv-n"></b><small class="lv-desc"></small></div>
    <button type="button" class="lv-step" data-d="1" aria-label="Harder level">▶</button>
    <small class="lv-unlocked"></small>`;
  const show = (n) => {
    box.querySelector(".lv-n").textContent = "Level " + n;
    box.querySelector(".lv-desc").textContent = describe(n);
    box.querySelector('[data-d="-1"]').disabled = n <= 1;
    box.querySelector('[data-d="1"]').disabled = n >= lv.unlocked();
    box.querySelector(".lv-unlocked").textContent = lv.unlocked() >= 20 ? "All 20 levels unlocked 🏆"
      : `Unlocked: 1–${lv.unlocked()} · win to unlock level ${lv.unlocked() + 1} 🔒`;
  };
  let n = lv.current();
  box.querySelectorAll(".lv-step").forEach((b) => b.onclick = () => {
    n = Math.max(1, Math.min(lv.unlocked(), n + +b.dataset.d)); lv.set(n); show(n); onChange && onChange(n);
  });
  show(n);
  return { level: () => n, refresh: () => { n = lv.current(); show(n); } };
};
// The scenery for a level, the same tiers in every game: sunrise, midday,
// evening (the original look), sunset and midnight. body: a sun or moon at
// (x, y) as fractions of the view.
window.ptcScene = (n) => [
  { name: "Sunrise", sky: ["#3b5b8c", "#f2a97e"], turf: ["#4fae6e", "#2a6b45"], edge: "#8be0a4", wood: ["#c99a64", "#7a5634"],
    body: { x: 0.16, y: 0.38, r: 0.035, color: "#ffd9a0" } },
  { name: "Midday", sky: ["#3f86d1", "#a9d4f5"], turf: ["#43a362", "#1f5a36"], edge: "#86dca0", wood: ["#c99a64", "#7a5634"],
    body: { x: 0.78, y: 0.16, r: 0.05, color: "#fff4c2" } },
  { name: "Evening", sky: ["#0f1a2b", "#1b2d44"], turf: ["#2f7d53", "#173a28"], edge: "#5fbf86", wood: ["#b98a56", "#6e4f2e"] },
  { name: "Sunset", sky: ["#2b1f4a", "#e86a4a"], turf: ["#2d6b47", "#14301f"], edge: "#79c08e", wood: ["#a8774a", "#5e3f22"],
    body: { x: 0.86, y: 0.36, r: 0.038, color: "#ff9e5e" } },
  { name: "Midnight", sky: ["#03050c", "#0b1530"], turf: ["#1d4a35", "#0b1d14"], edge: "#3f8f68", wood: ["#8a6a48", "#4a3622"],
    body: { x: 0.8, y: 0.18, r: 0.028, color: "#dfe6f5" }, stars: true },
][Math.min(4, Math.floor((Math.max(1, Math.min(20, n || 10)) - 1) / 4))];
// The player's name, kept in this browser for every game.
window.ptcName = {
  get: () => { try { return localStorage.getItem("ptc-name") || ""; } catch (e) { return ""; } },
  set: (v) => { try { localStorage.setItem("ptc-name", (v || "").trim()); } catch (e) {} },
};
try {
  if (!sessionStorage.getItem("ptc-visit")) {
    sessionStorage.setItem("ptc-visit", "1");
    const seen = localStorage.getItem("ptc-seen");
    localStorage.setItem("ptc-seen", "1");
    window.ptcTrack(seen ? "visit_return" : "visit_new");
  }
} catch (e) {}
</script>
""" + (f'<script defer src="https://cloud.umami.is/script.js" data-website-id="{UMAMI_ID}" data-domains="ne5l7-xiaaa-aaaaj-qsm3q-cai.icp0.io"></script>\n' if UMAMI_ID else "")
FABRIC_LINK = '<link rel="stylesheet" href="/fabric.css'
for name, file in PAGES.items():
    html = (ROOT / "src/ui" / file).read_text(encoding="utf-8")
    assert html.count(FABRIC_LINK) == 1, f"{file} needs the fabric link once"
    html = html.replace(FABRIC_LINK, OG_TAGS + TRACK + FABRIC_LINK).replace("__FABRIC_V__", version)
    assert ')HTML"' not in html, f"{file} must not contain the raw-string delimiter"
    out += f'\nstatic const char {name}[] = R"HTML({html})HTML";\n'
    print(f"{file}: {len(html.encode())} bytes of HTML")
# three.js (MIT, src/ui/vendor/three.LICENSE), served by the canister with a
# long cache, so the 3D page needs nothing from anywhere else.
js = (ROOT / "src/ui/vendor/three.module.min.js").read_text(encoding="utf-8")
assert ')JS"' not in js
out += f'\n#ifndef PTC_PLAYGROUND\nstatic const char THREE_JS[] = R"JS({js})JS";\n#endif\n'
print(f"three.module.min.js: {len(js.encode())} bytes")
# The preview images, 1200x630 JPEGs made in the launch-video project
# (ShareCard.tsx). Asked for with a hash of their bytes, like the fabric.
og = {k: (ROOT / f"src/ui/og/{k}.jpg").read_bytes() for k in ("home", "chess", "golf")}
og_version = hashlib.sha256(b"".join(og.values())).hexdigest()[:10]
out += f'\nstatic const char OG_V[] = "{og_version}";\n'
for k, data in og.items():
    body = ",".join(str(b) for b in data)
    out += f"\nstatic const unsigned char OG_{k.upper()}_JPG[] = {{{body}}};\n"
    print(f"og/{k}.jpg: {len(data)} bytes")
(ROOT / "src/ui_html.h").write_text(out, encoding="utf-8")
