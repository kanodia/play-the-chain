static std::string u128(__uint128_t v) {
  if (v == 0) return "0";
  std::string s;
  while (v) { s.insert(s.begin(), char('0' + int(v % 10))); v /= 10; }
  return s;
}

std::vector<FuelEntry> fuel_log() {
  std::vector<FuelEntry> out;
  std::ifstream file(LOG_PATH);
  std::string line;
  while (std::getline(file, line)) {
    std::istringstream in(line);
    FuelEntry e;
    std::string cycles;
    if (!(in >> e.time_ns >> e.e8s >> e.block >> cycles)) continue;
    for (char c : cycles) e.cycles = e.cycles * 10 + (c - '0');
    in >> e.dev_e8s >> e.dev_block; // absent in refuels from before the share
    out.push_back(e);
  }
  return out;
}

static void log_append(const FuelEntry &e) {
  std::ofstream file(LOG_PATH, std::ios::app);
  file << e.time_ns << ' ' << e.e8s << ' ' << e.block << ' ' << u128(e.cycles) << ' '
       << e.dev_e8s << ' ' << e.dev_block << '\n';
}

static void share_save(uint64_t block, uint64_t e8s) {
  std::ofstream file(SHARE_PATH, std::ios::trunc);
  if (block) file << block << ' ' << e8s;
}

static bool share_load(uint64_t &block, uint64_t &e8s) {
  std::ifstream file(SHARE_PATH);
  return file && (file >> block >> e8s);
}

static int hex_digit(char c) {
  return c >= '0' && c <= '9' ? c - '0' : c >= 'a' && c <= 'f' ? c - 'a' + 10 : c >= 'A' && c <= 'F' ? c - 'A' + 10 : -1;
}

// TRANSFER_PREFIX with another destination account and memo 0: the same
// transfer, to the developer.
static bool dev_transfer_args(std::vector<uint8_t> &args) {
  if (std::char_traits<char>::length(DEV_ACCOUNT) != 64) return false;
  args.assign(std::begin(TRANSFER_PREFIX), std::end(TRANSFER_PREFIX));
  // The values start after "1 argument of type 5"; `to` is a 32-byte blob.
  static const uint8_t AT[] = {0x01, 0x05, 0x20};
  auto it = std::search(args.begin(), args.end(), std::begin(AT), std::end(AT));
  if (it == args.end()) return false;
  size_t to = (it - args.begin()) + 3, memo = to + 32 + 8; // then the fee, then the memo
  for (size_t k = 0; k < 32; ++k) {
    int hi = hex_digit(DEV_ACCOUNT[2 * k]), lo = hex_digit(DEV_ACCOUNT[2 * k + 1]);
    if (hi < 0 || lo < 0) return false;
    args[to + k] = uint8_t(hi * 16 + lo);
  }
  for (size_t k = 0; k < 8; ++k) args[memo + k] = 0;
  return true;
}

static bool pending_load(uint64_t &block, uint64_t &e8s) {
  std::ifstream file(PENDING_PATH);
  return file && (file >> block >> e8s);
}

static void pending_save(uint64_t block, uint64_t e8s) {
  std::ofstream file(PENDING_PATH, std::ios::trunc);
  if (block) file << block << ' ' << e8s;
}

static std::string reply(bool ok, const std::string &message,
                         uint64_t e8s = 0, __uint128_t cycles = 0) {
  return std::string("{\"ok\":") + (ok ? "true" : "false") + ",\"message\":\"" +
         message + "\",\"e8s\":" + std::to_string(e8s) +
         ",\"cycles\":" + u128(cycles) + "}";
}

// The ledger and the CMC are NNS canisters, so the transfer and the notify are
// guaranteed-response calls: a transfer whose reply got lost would leave the
// ICP with the CMC, unclaimed. The balance check is best-effort.

// Asks the CMC for the cycles of a payment it already received.
static IC_Task<OkOrErr> notify(CandidTypePrincipal self, uint64_t block) {
  CandidTypeRecord arg;
  arg.append("block_index", CandidTypeNat64{block});
  arg.append("canister_id", self);
  IC_CallResult<IC_CallReply> r =
      co_await IC_Call::unbounded_wait(CandidTypePrincipal{CMC}, "notify_top_up")
          .with_arg(arg);
  if (!r) co_return OkOrErr{true, false, 0, "the CMC did not answer"};
  co_return decode_ok_or_err(r->bytes.vec(),
                             {"Refunded", "Processing", "TransactionTooOld",
                              "InvalidTransaction", "Other"});
}

void fuel_note_paid_share(uint64_t block, uint64_t e8s) {
  uint64_t b{0}, x{0};
  if (!fuel_log().empty() || share_load(b, x)) return;
  share_save(block, e8s);
}

// Why a call failed, for the page and the canister log. Quotes would break
// the JSON reply, so they go.
static std::string why(const IC_CallResult<IC_CallReply> &r) {
  std::string s = r.error().to_string();
  for (char &c : s)
    if (c == '"' || c == '\\' || c == '\n') c = ' ';
  return s;
}

// A refuel in flight. Set before the first call; it expires, in case a later
// message traps and never clears it.
static uint64_t g_busy_since_ns = 0;
constexpr uint64_t BUSY_TTL_NS = 10ULL * 60 * 1'000'000'000;

IC_Task<std::string> refuel(CandidTypePrincipal self) {
  if (self.get_text() != FUEL_PRINCIPAL)
    co_return reply(false, "the fuel accounts are set for another canister");
  uint64_t now = IC_API::time();
  if (g_busy_since_ns && now - g_busy_since_ns < BUSY_TTL_NS)
    co_return reply(false, "a refuel is already running, try again in a minute");
  g_busy_since_ns = now;

  // A payment from an earlier refuel whose cycles never arrived.
  uint64_t block{0}, e8s{0};
  if (!pending_load(block, e8s) || !block) {
    IC_CallResult<IC_CallReply> bal =
        co_await IC_Call::bounded_wait(CandidTypePrincipal{LEDGER},
                                       "account_balance")
            .with_raw_args({std::begin(BALANCE_ARGS), std::end(BALANCE_ARGS)});
    if (!bal) {
      g_busy_since_ns = 0;
      co_return reply(false, "the ICP ledger did not answer, try again (" + why(bal) + ")");
    }
    uint64_t balance{0};
    CandidTypeRecord tokens;
    tokens.append("e8s", CandidTypeNat64{&balance});
    bal->decode(tokens);
    if (balance < MIN_E8S + LEDGER_FEE) {
      g_busy_since_ns = 0;
      co_return reply(false, "no ICP waiting on the canister's account yet");
    }

    // The developer's share first, unless this refuel already paid it. If the
    // ledger refuses it, everything goes to the cycles this time.
    uint64_t share_block{0}, share{0};
    std::vector<uint8_t> dev;
    if (!share_load(share_block, share) && dev_transfer_args(dev)) {
      uint64_t cut = balance * DEV_SHARE_PERCENT / 100;
      if (cut > 2 * LEDGER_FEE) {
        for (int k = 0; k < 8; ++k) dev.push_back(uint8_t((cut - LEDGER_FEE) >> (8 * k)));
        IC_CallResult<IC_CallReply> dr =
            co_await IC_Call::unbounded_wait(CandidTypePrincipal{LEDGER}, "transfer")
                .with_raw_args(dev);
        if (!dr) IC_API::debug_print("fuel: the developer share was not sent: " + why(dr));
        if (dr) {
          OkOrErr d = decode_ok_or_err(dr->bytes.vec(), {"BadFee", "InsufficientFunds", "TxTooOld",
                                                         "TxCreatedInFuture", "TxDuplicate"});
          if (d.decoded && d.ok) {
            share = cut - LEDGER_FEE;
            share_block = static_cast<uint64_t>(d.value);
            share_save(share_block, share);
            balance -= cut;
          }
        }
      }
    }

    e8s = balance - LEDGER_FEE;
    std::vector<uint8_t> args(std::begin(TRANSFER_PREFIX), std::end(TRANSFER_PREFIX));
    for (int k = 0; k < 8; ++k) args.push_back(uint8_t(e8s >> (8 * k)));
    IC_CallResult<IC_CallReply> tr =
        co_await IC_Call::unbounded_wait(CandidTypePrincipal{LEDGER}, "transfer")
            .with_raw_args(args);
    if (!tr) {
      g_busy_since_ns = 0;
      IC_API::debug_print("fuel: the transfer to the CMC failed: " + why(tr));
      co_return reply(false, "the ICP ledger did not confirm the transfer (" + why(tr) + ")");
    }
    OkOrErr t = decode_ok_or_err(tr->bytes.vec(),
                                 {"BadFee", "InsufficientFunds", "TxTooOld",
                                  "TxCreatedInFuture", "TxDuplicate"});
    if (!t.decoded || !t.ok) {
      g_busy_since_ns = 0;
      co_return reply(false, "the ICP ledger refused the transfer: " + t.err);
    }
    block = static_cast<uint64_t>(t.value);
    pending_save(block, e8s);
  }

  OkOrErr n = co_await notify(self, block);
  g_busy_since_ns = 0;
  if (n.decoded && n.ok) {
    pending_save(0, 0);
    uint64_t share_block{0}, share{0};
    share_load(share_block, share);
    share_save(0, 0);
    log_append({IC_API::time(), e8s, block, n.value, share, share_block});
    co_return reply(true, "converted into cycles", e8s, n.value);
  }
  // Refunded and too-old payments are final; anything else is tried again by
  // the next refuel.
  if (n.err == "Refunded" || n.err == "TransactionTooOld" ||
      n.err == "InvalidTransaction")
    pending_save(0, 0);
  co_return reply(false, "the cycles minting canister said: " +
                             (n.err.empty() ? "no reply" : n.err),
                  e8s);
}
